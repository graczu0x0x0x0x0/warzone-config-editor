"""Build the Windows executable: ``uv run python scripts/build_exe.py [--onedir]``

Steps:
1. write Windows version resources (file properties -> Details) from ``wzce.__version__``
2. run PyInstaller (windowed, app icon, bundled ``wzce`` data: knowledge base, i18n, icons)
3. run the built exe with ``--smoke-test`` (headless) - a broken build fails here, not on
   the user's PC
4. copy the result to ``dist/WarzoneConfigEditor-<version>.exe`` and write its SHA-256

Default is a single-file exe (easy to share). ``--onedir`` builds a folder instead: it
starts faster and antivirus programs flag it less often than one-file builds.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from wzce import __version__  # noqa: E402

APP_NAME = "WarzoneConfigEditor"
BUILD = ROOT / "build"
DIST = ROOT / "dist"
ICON = ROOT / "src" / "wzce" / "data" / "icons" / "app.ico"

VERSION_TEMPLATE = """# UTF-8 - generated by scripts/build_exe.py, do not edit
VSVersionInfo(
  ffi=FixedFileInfo(filevers={tuple}, prodvers={tuple}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'Warzone Config Editor'),
      StringStruct('FileDescription', 'Warzone Config Editor - Call of Duty settings editor'),
      StringStruct('FileVersion', '{version}'),
      StringStruct('InternalName', '{name}'),
      StringStruct('OriginalFilename', '{name}.exe'),
      StringStruct('ProductName', 'Warzone Config Editor'),
      StringStruct('ProductVersion', '{version}'),
      StringStruct('LegalCopyright', 'Not affiliated with Activision')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def version_tuple(version: str) -> tuple[int, int, int, int]:
    parts = [int("".join(ch for ch in p if ch.isdigit()) or 0) for p in version.split(".")]
    return tuple([*parts, 0, 0, 0, 0][:4])  # type: ignore[return-value]


def write_version_file() -> Path:
    BUILD.mkdir(exist_ok=True)
    path = BUILD / "version_info.txt"
    path.write_text(
        VERSION_TEMPLATE.format(
            tuple=version_tuple(__version__), version=__version__, name=APP_NAME
        ),
        encoding="utf-8",
    )
    return path


def run_pyinstaller(version_file: Path, onedir: bool) -> Path:
    command = [
        sys.executable, "-m", "PyInstaller",
        "--noconfirm", "--clean", "--windowed",
        "--onedir" if onedir else "--onefile",
        "--name", APP_NAME,
        "--icon", str(ICON),
        "--version-file", str(version_file),
        "--paths", str(ROOT / "src"),
        "--collect-data", "wzce",
        "--exclude-module", "tkinter",
        "--distpath", str(DIST),
        "--workpath", str(BUILD / "pyinstaller"),
        "--specpath", str(BUILD),
        str(ROOT / "scripts" / "launcher.py"),
    ]  # fmt: skip
    subprocess.run(command, check=True, cwd=ROOT)
    if onedir:
        return DIST / APP_NAME / f"{APP_NAME}.exe"
    return DIST / f"{APP_NAME}.exe"


def smoke_test(exe: Path) -> None:
    env = dict(os.environ, QT_QPA_PLATFORM="offscreen")
    result = subprocess.run([str(exe), "--smoke-test"], env=env, timeout=180, check=False)
    if result.returncode != 0:
        raise SystemExit(f"smoke test FAILED with exit code {result.returncode}")
    print("smoke test passed")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--onedir", action="store_true", help="build a folder instead of one exe")
    args = parser.parse_args()

    exe = run_pyinstaller(write_version_file(), args.onedir)
    smoke_test(exe)

    if args.onedir:
        archive = shutil.make_archive(
            str(DIST / f"{APP_NAME}-{__version__}"), "zip", DIST, APP_NAME
        )
        artifact = Path(archive)
    else:
        artifact = DIST / f"{APP_NAME}-{__version__}.exe"
        shutil.copy2(exe, artifact)
    digest = hashlib.sha256(artifact.read_bytes()).hexdigest()
    artifact.with_name(artifact.name + ".sha256").write_text(
        f"{digest}  {artifact.name}\n", encoding="utf-8"
    )
    size_mb = artifact.stat().st_size / 1024 / 1024
    print(f"built {artifact.relative_to(ROOT)} ({size_mb:.1f} MB)\nsha256 {digest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
